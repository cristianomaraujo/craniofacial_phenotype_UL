"""## 5. Cluster tendency: Dip test and Hopkins statistic"""

def hopkins_statistic(x, repetitions=200, fraction=0.10, seed=SEED):
    vals = []
    for i in range(repetitions):
        rng = np.random.default_rng(seed + i)
        m = min(max(5, int(np.ceil(fraction * len(x)))), len(x) - 1)
        idx = rng.choice(len(x), m, replace=False)

        artificial = rng.uniform(
            x.min(axis=0), x.max(axis=0),
            size=(m, x.shape[1])
        )

        dr = cdist(x[idx], x)
        dr[np.arange(m), idx] = np.inf
        w = dr.min(axis=1).sum()
        u = cdist(artificial, x).min(axis=1).sum()
        vals.append(u / (u + w))

    return np.asarray(vals)

