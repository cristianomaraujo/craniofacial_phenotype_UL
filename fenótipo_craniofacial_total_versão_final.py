def cramers_v(table):
    chi2_stat, p, dof, expected = stats.chi2_contingency(table)
    n = table.to_numpy().sum()
    r, k = table.shape
    denom = n * min(k - 1, r - 1)
    v = np.sqrt(chi2_stat / denom) if denom > 0 else np.nan
    return {
        "Chi_square": chi2_stat,
        "df": dof,
        "p_value": p,
        "Cramers_V": v
    }

