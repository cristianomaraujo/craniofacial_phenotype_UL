"""## 6. Gap Statistic — k = 1 to 10

The 1-SE rule is allowed to select **k = 1**, which is interpreted as no supported partition.

"""

def gap_statistic(x, k_max=K_MAX, B=GAP_B, seed=SEED):
    rng = np.random.default_rng(seed)
    rows = []

    for k in range(1, k_max + 1):
        print(f"k={k}/{k_max}")
        km = KMeans(n_clusters=k, n_init=100, random_state=seed).fit(x)
        obs = np.log(max(km.inertia_, np.finfo(float).eps))

        refs = []
        for b in range(B):
            ref = rng.uniform(x.min(axis=0), x.max(axis=0), size=x.shape)
            kr = KMeans(
                n_clusters=k,
                n_init=20,
                random_state=seed + b + 1000 * k
            ).fit(ref)
            refs.append(np.log(max(kr.inertia_, np.finfo(float).eps)))

        rows.append({
            "k": k,
            "Gap": np.mean(refs) - obs,
            "SE": np.std(refs, ddof=1) * np.sqrt(1 + 1 / B)
        })

    res = pd.DataFrame(rows)

    selected = None
    for i in range(len(res) - 1):
        if res.loc[i, "Gap"] >= res.loc[i + 1, "Gap"] - res.loc[i + 1, "SE"]:
            selected = int(res.loc[i, "k"])
            break

    if selected is None:
        selected = int(res.loc[res["Gap"].idxmax(), "k"])

    return res, selected

