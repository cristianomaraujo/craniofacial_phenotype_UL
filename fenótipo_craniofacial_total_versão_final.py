"""## 10. Bootstrap 95% confidence intervals for primary cluster means

For SNA, SNB and SN.GoGn, confidence intervals are used to characterize the precision of each cluster mean, **not** to test whether the clusters differ.

At every bootstrap iteration:

1. participants are sampled with replacement from the full analytical sample;
2. discovery variables are re-standardized;
3. PCA is re-estimated using the same ≥95% cumulative-variance rule;
4. K-means is refitted using the primary k;
5. bootstrap labels are aligned to the original cluster solution using the Hungarian algorithm and standardized-variable centroids;
6. cluster means are calculated in the original degree scale.

The reported 95% CIs are percentile intervals (2.5th–97.5th percentiles) across successful bootstrap replicates.

"""

def align_bootstrap_labels(reference_centroids_z, boot_centroids_z):
    # rows = bootstrap clusters; columns = reference clusters
    cost = cdist(boot_centroids_z, reference_centroids_z, metric="euclidean")
    row_ind, col_ind = linear_sum_assignment(cost)
    return {row: col + 1 for row, col in zip(row_ind, col_ind)}

def bootstrap_cluster_mean_ci(
    data,
    discovery_vars,
    k,
    B=BOOTSTRAP_CI_B,
    seed=SEED
):
    if k < 2:
        raise ValueError("Bootstrap cluster CIs require a supported partition with k >= 2.")

    # Reference solution in standardized raw-variable space
    ref_scaler = StandardScaler()
    ref_z = ref_scaler.fit_transform(data[discovery_vars])

    ref_pca = PCA(svd_solver="full")
    ref_pc = ref_pca.fit_transform(ref_z)
    if ref_pca.components_[0].sum() < 0:
        ref_pca.components_[0] *= -1
        ref_pc[:, 0] *= -1

    ref_cum = np.cumsum(ref_pca.explained_variance_ratio_)
    ref_n_pc = int(np.searchsorted(ref_cum, 0.95) + 1)
    ref_x = ref_pc[:, :ref_n_pc]

    ref_raw = KMeans(
        n_clusters=k,
        n_init=100,
        random_state=seed
    ).fit_predict(ref_x)

    ref_order = (
        pd.DataFrame({"raw": ref_raw, "PC1": ref_pc[:, 0]})
        .groupby("raw")["PC1"]
        .mean()
        .sort_values()
        .index
        .tolist()
    )
    ref_map = {old: new + 1 for new, old in enumerate(ref_order)}
    ref_labels = np.array([ref_map[x] for x in ref_raw], dtype=int)

    ref_centroids_z = np.vstack([
        ref_z[ref_labels == cl].mean(axis=0)
        for cl in range(1, k + 1)
    ])

    rng = np.random.default_rng(seed)
    rows = []
    failed = 0

    for b in range(B):
        idx = rng.choice(len(data), size=len(data), replace=True)
        boot = data.iloc[idx].reset_index(drop=True)

        try:
            b_scaler = StandardScaler()
            bz = b_scaler.fit_transform(boot[discovery_vars])

            b_pca = PCA(svd_solver="full")
            bpc = b_pca.fit_transform(bz)

            if b_pca.components_[0].sum() < 0:
                b_pca.components_[0] *= -1
                bpc[:, 0] *= -1

            bcum = np.cumsum(b_pca.explained_variance_ratio_)
            bn_pc = int(np.searchsorted(bcum, 0.95) + 1)
            bx = bpc[:, :bn_pc]

            b_raw = KMeans(
                n_clusters=k,
                n_init=100,
                random_state=seed + b + 1
            ).fit_predict(bx)

            if len(np.unique(b_raw)) != k:
                failed += 1
                continue

            # Convert bootstrap centroids back to the REFERENCE standardized scale
            raw_boot_means = np.vstack([
                boot.loc[b_raw == cl, discovery_vars].mean().to_numpy(dtype=float)
                for cl in range(k)
            ])
            boot_centroids_ref_z = ref_scaler.transform(raw_boot_means)

            label_map = align_bootstrap_labels(
                ref_centroids_z,
                boot_centroids_ref_z
            )
            aligned = np.array([label_map[x] for x in b_raw], dtype=int)

            for cl in range(1, k + 1):
                mask = aligned == cl
                if mask.sum() == 0:
                    continue

                for var in discovery_vars:
                    rows.append({
                        "Iteration": b + 1,
                        "Cluster": cl,
                        "Variable": var,
                        "Mean": boot.loc[mask, var].mean()
                    })

        except Exception:
            failed += 1

    boot_means = pd.DataFrame(rows)

    ci = (
        boot_means
        .groupby(["Cluster", "Variable"])["Mean"]
        .agg(
            Bootstrap_mean="mean",
            CI95_lower=lambda x: np.percentile(x, 2.5),
            CI95_upper=lambda x: np.percentile(x, 97.5),
            Successful_replicates="count"
        )
        .reset_index()
    )

    observed = (
        primary_data
        .groupby("Cluster")[discovery_vars]
        .mean()
        .stack()
        .rename("Observed_mean")
        .reset_index()
        .rename(columns={"level_1": "Variable"})
    )

    ci = observed.merge(ci, on=["Cluster", "Variable"], how="left")

    return ci, boot_means, failed

